            onClick={handleNext}
            className="mt-4 bg-indigo-600 text-white px-6 py-3 rounded-2xl hover:bg-indigo-800 transition hover:cursor-pointer font-bold disabled:bg-neutral-500 disabled:cursor-not-allowed"
